# --- Автоматическое московское время в system prompt (для всех моделей) ---

import datetime as dt

try:
    from zoneinfo import ZoneInfo
    _MSK_TZ = ZoneInfo("Europe/Moscow")
except Exception:  # pragma: no cover
    _MSK_TZ = None  # type: ignore

_RU_MONTHS_GEN = {
    1: "января", 2: "февраля", 3: "марта", 4: "апреля",
    5: "мая", 6: "июня", 7: "июля", 8: "августа",
    9: "сентября", 10: "октября", 11: "ноября", 12: "декабря",
}

_RU_WEEKDAYS = {
    0: "Понедельник", 1: "Вторник", 2: "Среда", 3: "Четверг",
    4: "Пятница", 5: "Суббота", 6: "Воскресенье",
}


def _get_moscow_now_str() -> str:
    """Возвращает строку текущего времени по Москве.

    Формат: "27 мая 2026, 22:47:12 MSK (UTC+3) | Среда"
    """
    try:
        if _MSK_TZ is not None:
            now = dt.datetime.now(_MSK_TZ)
        else:
            raise RuntimeError("no zoneinfo")
        tz_label = "MSK"
        offset = "+3"
    except Exception:
        # Fallback: ручной сдвиг (Moscow постоянный UTC+3 с 2014)
        now = dt.datetime.utcnow() + dt.timedelta(hours=3)
        tz_label = "MSK"
        offset = "+3"

    date_part = f"{now.day} {_RU_MONTHS_GEN[now.month]} {now.year}"
    time_part = now.strftime("%H:%M:%S")
    weekday = _RU_WEEKDAYS.get(now.weekday(), "")

    return f"{date_part}, {time_part} {tz_label} (UTC{offset}) | {weekday}"


# Сильная директива про время — кладётся в самое начало system prompt.
# Это нужно, чтобы даже слабые модели (типа GLM) не пытались искать время через web_search
# и не путались в датах.
_TIME_DIRECTIVE = """\
[ТЕКУЩЕЕ ВРЕМЯ — ИСПОЛЬЗУЙ ТОЛЬКО ЕГО, НЕ ИЩИ В ИНТЕРНЕТЕ]
Сейчас: {time}

СТРОГИЕ ПРАВИЛА (приоритет выше всего остального):
- Это точное и актуальное время в Москве. Всегда используй только его.
- Если пользователь спрашивает "который час", "сколько времени", "текущее время", "дата сегодня" и т.п. — отвечай ТОЛЬКО на основе строки выше. Коротко и точно.
- КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО вызывать инструмент web_search по любым запросам про время, дату, "Москва сейчас", "сколько сейчас" и подобным. Это не "свежая информация" — это уже дано выше.
- Никогда не пиши другое время и не говори "я не знаю точное время".
"""


def get_system_prompt(chat_type: str) -> str:
    """Возвращает system prompt с текущим московским временем + жёсткой инструкцией."""
    time_str = _get_moscow_now_str()
    directive = _TIME_DIRECTIVE.format(time=time_str)

    if chat_type in ("group", "supergroup"):
        base = GROUP_SYSTEM_PROMPT
    else:
        base = PRIVATE_SYSTEM_PROMPT

    # Директива времени — всегда самой первой в промпте
    return f"{directive}\n{base}"
